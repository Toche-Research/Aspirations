"""Table of asset-pricing moments for 'Ex Ante Aspirations' (writes out/tables/tbl_asset_pricing.tex).

Endowment economy, annual period, log consumption growth iid N(mu, sigma^2) with the Mehra-Prescott (1985,
Table 1, 1889-1978) moments mu = 1.83%, sigma = 3.57%; beta = 0.97. Aspirations for year t+1 are set in year t.
Moments are exact (lognormal formulas, Proposition 4) except for the consumption claim, whose unconditional
moments are computed by two-dimensional Gauss-Hermite quadrature from its exact price-consumption ratio.
"""
import numpy as np
from pathlib import Path

MU, SIGMA, BETA = 0.0183, 0.0357, 0.97
DATA = dict(rf_mean=0.80, rf_sd=5.67, eq_prem=6.18, eq_sd=16.54)   # Mehra-Prescott (1985), Table 1, percent

x, w = np.polynomial.hermite_e.hermegauss(60)
w = w / w.sum()


def moments(gamma, Delta, beta=BETA, mu=MU, sigma=SIGMA):
    """Asset-pricing moments of the endowment economy for one (gamma, Delta) pair, in logs or levels.

    Returns the mean and standard deviation of the log risk-free rate, the log premium on a one-year
    consumption strip and the per-year log premium on long strips, the excess return and standard
    deviation of the consumption claim, its Sharpe ratio and its price-consumption ratio at mean growth.
    The risk-free and strip moments are the exact lognormal formulas of Proposition 4; the consumption
    claim is integrated by two-dimensional Gauss-Hermite quadrature from its exact price-consumption
    ratio, which loads (gamma - Delta) on the current growth shock.  The Sharpe ratio is returned for
    inspection and is not printed in the table.
    """
    rf_mean = -np.log(beta) + Delta * mu - 0.5 * gamma ** 2 * sigma ** 2     # log risk-free rate, mean
    rf_sd = (gamma - Delta) * sigma
    strip1 = gamma * sigma ** 2                                                # log premium, one-year strip
    strip_inf = Delta * sigma ** 2                                             # per year, long strips
    q = np.exp(np.log(beta) + (1 - Delta) * mu + 0.5 * (1 - Delta) ** 2 * sigma ** 2)
    assert q < 1
    K = np.exp(np.log(beta) + (1 - gamma) * mu + 0.5 * (1 - gamma) ** 2 * sigma ** 2) / (1 - q)
    # returns on the consumption claim: R' = e^{dc'} (1 + K e^{(g-D) dc'}) / (K e^{(g-D) dc})
    dc0 = mu + sigma * x[:, None]          # dc_t
    dc1 = mu + sigma * x[None, :]          # dc_{t+1}
    W = w[:, None] * w[None, :]
    R = np.exp(dc1) * (1 + K * np.exp((gamma - Delta) * dc1)) / (K * np.exp((gamma - Delta) * dc0))
    Rf = np.exp(-np.log(beta) + Delta * mu - (gamma - Delta) * (dc0 - mu) - 0.5 * gamma ** 2 * sigma ** 2) * np.ones_like(R)
    ER, ERf = np.sum(W * R), np.sum(W * Rf)
    sdR = np.sqrt(np.sum(W * (R - ER) ** 2))
    ex = R - Rf
    sharpe = np.sum(W * ex) / np.sqrt(np.sum(W * (ex - np.sum(W * ex)) ** 2))
    pc = K * np.exp((gamma - Delta) * mu)                                     # price/consumption at mean growth
    return dict(rf_mean=100 * rf_mean, rf_sd=100 * rf_sd, strip1=100 * strip1, strip_inf=100 * strip_inf,
                cc_prem=100 * (ER - ERf), cc_sd=100 * sdR, sharpe=sharpe, pc=pc)


ROWS = [  # (label, gamma, Delta); aspirations rows use the isoelastic example, theta = (gamma-1)/(1-Delta)
    ('Power utility', 2.0, 2.0),
    ('Power utility', 10.0, 10.0),
    ('Aspirations', 2.0, 0.5),
    ('Aspirations', 2.5, 0.9),
    ('Aspirations', 5.0, 0.5),
    ('Aspirations', 10.0, 0.5),
]

if __name__ == '__main__':
    lines = []
    for label, g, D in ROWS:
        m = moments(g, D)
        th = '' if D == g else f"{(g - 1) / (1 - D):.3g}"
        lines.append(f"{label} & {g:g} & {th} & {1 / D:.3g} & {m['rf_mean']:.2f} & {m['rf_sd']:.2f} & {m['strip1']:.2f} & "
                     f"{m['strip_inf']:.2f} & {m['cc_prem']:.2f} & {m['cc_sd']:.2f} & {m['pc']:.0f} \\\\")
        print(lines[-1])
    lines.append('\\midrule')
    lines.append(f"Data (1889--1978) & & & & {DATA['rf_mean']:.2f} & {DATA['rf_sd']:.2f} & & & "
                 f"{DATA['eq_prem']:.2f} & {DATA['eq_sd']:.2f} & \\\\")
    out = Path(__file__).resolve().parents[1] / 'out' / 'tables' / 'tbl_asset_pricing.tex'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('% generated by code/table_asset_pricing.py; do not edit\n' + '\n'.join(lines) + '\n')
    print('wrote', out)
