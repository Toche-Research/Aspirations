"""Tables that describe the data of "Ex Ante Aspirations, Risk Aversion, and Intertemporal Substitution":
for each series, the source, the period, the number of observations, the mean and the standard deviation.

Run from code/ with PYTHONPATH=. after bound_curve.py, which writes the assembled United States series
that this script reads (out/data/bound_curve_data_quarterly.csv and bound_curve_data_annual.csv).  The
international series are read from data/yogo2004/ with the loader of yogo.py, so the rows described are
those the estimates use.

Writes, in out/data_description/:
  tbl_dd_us.tex, tbl_dd_yogo.tex     the two tables of the working paper
  data_description.md                the same tables in Markdown (copied to data/DATA_DESCRIPTION.md)
  data_description.json              every number, unrounded
"""
import os, json
import numpy as np
import pandas as pd
from aspirations import DATA, OUT, ODATA
from yogo import SERIES, load as yogo_load

DD = os.path.join(OUT, "data_description")
os.makedirs(DD, exist_ok=True)
GEN = "% generated by code/scripts/data_description.py; do not edit\n"

# ------------------------------------------------------------------ United States
# (column, label for LaTeX, label for Markdown, source)
SPF = "SPF"
RT = "Real-time"
QUARTERLY = [
    ("mu", "Expected growth, current quarter", SPF),
    ("mu_next", "Expected growth, next quarter", SPF),
    ("pi_e", "Expected inflation over the bill's life", SPF),
    ("disp", "Dispersion of the growth forecasts", SPF),
    ("g", "Growth of real consumption, first release", RT),
    ("e", "Growth surprise", SPF + ", " + RT),
    ("tbill", "Three-month Treasury bill rate", "FRED"),
    ("r", "Ex ante real bill rate", "FRED, " + SPF),
    ("r_expost", "Ex post real bill rate", "FRED"),
    ("g_pce", "Growth of real consumption per capita", "FRED"),
]
ANNUAL = [
    ("r_feb", "Ex ante real one-year rate, February", "FRED"),
    ("r_feb_expost", "Ex post real one-year rate, February", "FRED"),
    ("mu_q1", "Expected growth over the year, first-quarter survey", SPF),
    ("g", "Growth of real consumption over the year, first release", RT),
    ("e_q1", "Growth surprise over the year", SPF + ", " + RT),
    ("g_pce", "Growth of real consumption per capita", "FRED"),
]


def describe(frame, spec, freq):
    rows = []
    for col, label, source in spec:
        s = pd.to_numeric(frame[col], errors="coerce").dropna()
        rows.append(dict(variable=col, label=label, source=source, frequency=freq, first=str(s.index[0]), last=str(s.index[-1]),
                         n=int(len(s)), mean=float(s.mean()), sd=float(s.std())))
    return rows


q = pd.read_csv(os.path.join(ODATA, "bound_curve_data_quarterly.csv"), index_col=0)
a = pd.read_csv(os.path.join(ODATA, "bound_curve_data_annual.csv"), index_col=0)
us = describe(q, QUARTERLY, "quarterly") + describe(a, ANNUAL, "annual")

with open(os.path.join(DD, "tbl_dd_us.tex"), "w") as f:
    f.write(GEN + "\\begin{tabular}{llllrrr}\n\\toprule\nSeries & Source & First & Last & Obs. & Mean & S.d.\\\\\n")
    for freq, head in (("quarterly", "Quarterly"), ("annual", "Annual")):
        f.write("\\midrule\n\\multicolumn{7}{l}{\\emph{" + head + "}}\\\\\n")
        for r in us:
            if r["frequency"] == freq:
                f.write(f"{r['label']} & {r['source']} & {r['first']} & {r['last']} & {r['n']} & {r['mean']:.2f} & {r['sd']:.2f}\\\\\n")
    f.write("\\bottomrule\n\\end{tabular}\n")

# ------------------------------------------------------------------ international data of Yogo (2004)
NAMES = dict(USA="United States", AUL="Australia", CAN="Canada", FR="France", GER="Germany", ITA="Italy", JAP="Japan",
             NTH="Netherlands", SWD="Sweden", SWT="Switzerland", UK="United Kingdom")


def date(x, freq):
    y = int(x)
    return f"{y}Q{int(round((x - y) * 10))}" if freq == "Q" else str(y)


yg = []
for ctry, freq, short in SERIES:
    d = yogo_load(ctry, freq, short)
    k = 400 if freq == "Q" else 100          # per cent a year
    yg.append(dict(file=f"{ctry}{freq}.txt", country=NAMES[ctry], frequency="quarterly" if freq == "Q" else "annual",
                   short=bool(short), first=date(d["DATE"][0], freq), last=date(d["DATE"][-1], freq), n=int(len(d["DATE"])),
                   mean_dc=float(k * d["dc"].mean()), sd_dc=float(k * d["dc"].std(ddof=1)),
                   mean_rrf=float(k * d["rrf"].mean()), sd_rrf=float(k * d["rrf"].std(ddof=1)),
                   mean_rr=float(k * d["rr"].mean()), sd_rr=float(k * d["rr"].std(ddof=1))))

with open(os.path.join(DD, "tbl_dd_yogo.tex"), "w") as f:
    f.write(GEN + "\\begin{tabular}{lllrrrrrrr}\n\\toprule\n"
            " & & & & \\multicolumn{2}{c}{Consumption growth} & \\multicolumn{2}{c}{Real interest rate} & \\multicolumn{2}{c}{Real stock return}\\\\\n"
            "\\cmidrule(lr){5-6}\\cmidrule(lr){7-8}\\cmidrule(lr){9-10}\n"
            "Country & First & Last & Obs. & Mean & S.d. & Mean & S.d. & Mean & S.d.\\\\\n")
    for freq, head in (("quarterly", "Quarterly"), ("annual", "Annual")):
        f.write("\\midrule\n\\multicolumn{10}{l}{\\emph{" + head + "}}\\\\\n")
        for r in yg:
            if r["frequency"] == freq:
                f.write(f"{r['country']}{' (from 1970)' if r['short'] else ''} & {r['first']} & {r['last']} & {r['n']} & {r['mean_dc']:.1f} & {r['sd_dc']:.1f} & "
                        f"{r['mean_rrf']:.1f} & {r['sd_rrf']:.1f} & {r['mean_rr']:.1f} & {r['sd_rr']:.1f}\\\\\n")
    f.write("\\bottomrule\n\\end{tabular}\n")

json.dump(dict(united_states=us, yogo=yg), open(os.path.join(DD, "data_description.json"), "w"), indent=1)

# ------------------------------------------------------------------ Markdown
L = ["# Data description", "",
     "Written by `code/scripts/data_description.py`; do not edit. The same tables are in the appendix of the working paper.", "",
     "## United States: survey expectations, interest rates and consumption", "",
     "All series are in per cent a year. SPF: Survey of Professional Forecasters, Federal Reserve Bank of Philadelphia (`spf/`).",
     "Real-time: first releases of the growth of real consumption, Federal Reserve Bank of Philadelphia (`spf/rcon_first_second_third.xlsx`).",
     "FRED: `fred/`. Each row covers the observations of the series itself; the regressions use the quarters in which",
     "all their variables are present. The column \"Variable\" is the name of the series in `code/out/data/bound_curve_data_quarterly.csv`",
     "and `bound_curve_data_annual.csv`.", "",
     "| Series | Variable | Source | Frequency | First | Last | Observations | Mean | S.d. |", "|---|---|---|---|---|---|---:|---:|---:|"]
for r in us:
    L.append(f"| {r['label']} | `{r['variable']}` | {r['source']} | {r['frequency']} | {r['first']} | {r['last']} | {r['n']} | {r['mean']:.2f} | {r['sd']:.2f} |")
L += ["", "## International data of Yogo (2004)", "",
      "The rows that the estimates use: observations with a missing value of any variable or instrument are dropped, as in",
      "Yogo's programs. Log growth and log returns, in per cent a year (quarterly values are multiplied by four). The second",
      "United States quarterly series starts in 1970, as in Yogo's short sample.", "",
      "| File | Country | Frequency | First | Last | Observations | Consumption growth: mean | s.d. | Real interest rate: mean | s.d. | Real stock return: mean | s.d. |",
      "|---|---|---|---|---|---:|---:|---:|---:|---:|---:|---:|"]
for r in yg:
    L.append(f"| `{r['file']}` | {r['country']}{' (from 1970)' if r['short'] else ''} | {r['frequency']} | {r['first']} | {r['last']} | {r['n']} | "
             f"{r['mean_dc']:.1f} | {r['sd_dc']:.1f} | {r['mean_rrf']:.1f} | {r['sd_rrf']:.1f} | {r['mean_rr']:.1f} | {r['sd_rr']:.1f} |")
text = "\n".join(L) + "\n"
open(os.path.join(DD, "data_description.md"), "w").write(text)
open(os.path.join(DATA, "DATA_DESCRIPTION.md"), "w").write(text)
print("wrote", DD)
